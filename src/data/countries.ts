/**
 * Get all countries
 */
export function getCountries(): Country[] {
  return COUNTRIES;
}

/**
 * Get regions for a specific country code
 */
export function getRegions(countryCode: string): string[] {
  const country = COUNTRIES.find((c) => c.code === countryCode);
  return country?.regions ?? [];
}

/**
 * Get country name by code
 */
export function getCountryName(code: string): string {
  const country = COUNTRIES.find((c) => c.code === code);
  return country?.name ?? code;
}

/**
 * Get region name by country code and region
 * (Useful if you need to validate a region belongs to a country)
 */
export function getRegionName(countryCode: string, region: string): string | null {
  const regions = getRegions(countryCode);
  return regions.includes(region) ? region : null;
}

